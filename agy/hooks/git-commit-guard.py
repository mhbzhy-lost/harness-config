#!/usr/bin/env python3
"""AGY PreToolUse hook: 校验 git commit 提交信息是否符合 harness-config Git Commit 规范。

- 仅拦截 run_command 工具（工具名缺失时兜底检查 args.CommandLine）且 CommandLine 为非空字符串
- 解析复合命令（&& / || / ; / | / 换行 / 子 shell 括号），尊重单双引号与反斜杠转义
- 递归检查 sh / bash / zsh 的 -c（含 -lc 等组合短参数）嵌套命令
- 剥离 VAR=val / env / sudo / command / nohup / time 前缀后识别 git / git1（含 */git 绝对路径）
- 跳过 git 全局选项（-C / -c / --git-dir 等带值选项及 --no-pager / -p 等布尔选项）后仅校验 commit 子命令
- 提交信息须满足 agy/rules/harness-config.md 的 Git Commit 规范：
  type(scope): 中文祈使句、subject ≤ 50 字、不以句号结尾、非过去时、非零信息词、全量禁止 AI 署名
- 拒绝 -F / --file（无法静态校验），拒绝缺省 -m / --message 的提交（--amend --no-edit 与 --help 除外）
- 拒绝 $'...' 与命令替换（$() / 反引号）绕过；单引号内的字面 $() / 反引号允许
- 任何输入解析异常均 fail-open 返回 {"decision": "allow"}，不阻塞会话
"""

import json
import re
import sys

ALLOWED_TYPES = {
    "feat", "fix", "refactor", "perf", "test", "docs",
    "style", "chore", "build", "ci", "revert",
}
ZERO_INFO_SUBJECTS = {"fix", "update", "bugfix", "wip", "修改", "更新"}
CHINESE_RE = re.compile(r"[\u4e00-\u9fff]")
SUBJECT_RE = re.compile(r"^([a-zA-Z]+)(\(([^)]*)\))?:\s*(.*)$")
_PAST_VERBS = (
    r"(?:修复|实现|增加|更新|添加|删除|移除|重构|优化|调整|完善|解决|处理|"
    r"修改|改进|支持|完成|合并|升级|迁移|替换|清理|修正|补充|新增)"
)
PAST_VERB_RE = re.compile(r"^" + _PAST_VERBS + r"了")
# 过去时「已+动词」仅限已知祈使动词集，避免误杀「已读回执」等非过去时词
PAST_DONE_RE = re.compile(r"^已" + _PAST_VERBS)
AI_COAUTHOR_RE = re.compile(r"^co-authored-by:", re.IGNORECASE)
AI_NAME_RE = re.compile(
    r"\b(?:claude|copilot|cursor|chatgpt|openai|gemini|antigravity|codex|anthropic|ai)\b",
    re.IGNORECASE,
)
# 仅拦截含 AI 标识的 Generated with/by：后接 AI 名称，或 🤖 前缀；避免误伤 generated by protoc 等正常说明
AI_GENERATED_RE = re.compile(r"generated\s+(?:with|by)\b([^\n]*)", re.IGNORECASE)
AI_ROBOT_GENERATED_RE = re.compile(r"🤖\s*generated\s+(?:with|by)\b", re.IGNORECASE)
AI_ASSISTED_RE = re.compile(r"ai[-\s]?assisted", re.IGNORECASE)

# git 全局带值选项（--opt=val 与 --opt val 两种形式）
GIT_VALUE_OPTS = {
    "-C", "-c", "--git-dir", "--work-tree", "--namespace",
    "--config-env", "--super-prefix",
}
# git 全局布尔选项
GIT_BOOL_OPTS = {
    "--no-pager", "-p", "--paginate", "--bare", "--no-replace-objects",
    "--literal-pathspecs", "--glob-pathspecs", "--noglob-pathspecs",
    "--icase-pathspecs", "--no-optional-locks", "--no-lazy-fetch",
}
# commit 子命令中带值的长选项（--opt=val 形式只消耗自身）
COMMIT_VALUE_LONG = {
    "--template", "--reuse-message", "--reedit-message", "--fixup",
    "--squash", "--cleanup", "--pathspec-from-file", "--trailer",
}
SHELL_NAMES = {"sh", "bash", "zsh"}
# shell -c 载荷仅在涉及 git/git1/commit 时才因命令替换/ANSI-C 引用拒绝，避免误杀 bash -c "echo $(pwd)"
SHELL_PAYLOAD_GIT_RE = re.compile(r"\b(?:git1?|commit)\b")
SUDO_VALUE_OPTS = {"-u", "-g", "-p", "-h", "-D", "-R", "-C", "-T", "-r", "-t", "-U"}
ENV_VALUE_OPTS = {"-u", "-C"}
ENV_ASSIGN_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*=")
MAX_DEPTH = 8

REASON_SUBST = (
    "提交命令含命令替换 $() 或反引号，无法静态校验提交信息，违反 Git Commit 规范的可校验性要求；"
    "请改用单引号包裹的字面 -m 消息。"
)
REASON_ANSI = (
    "提交命令使用 $'...' ANSI-C 引用，无法静态校验提交信息；"
    "请改用普通单引号或双引号包裹的 -m 消息。"
)
REASON_FILE = (
    "git commit 使用 -F/--file 从文件读取提交信息，无法静态校验；"
    "请改用 -m/--message 直接传入符合规范的提交信息。"
)
REASON_NO_MESSAGE = (
    "git commit 缺少 -m/--message，无法静态校验提交信息；"
    "请显式传入 -m 'type(scope): 中文祈使句'（沿用原信息仅限 --amend --no-edit）。"
)


class Token:
    """shell 词元：text 为去引号后的文本，dynamic 标记含命令替换，ansi_c 标记 $'...'。"""

    __slots__ = ("text", "dynamic", "ansi_c")

    def __init__(self, text: str, dynamic: bool = False, ansi_c: bool = False):
        self.text = text
        self.dynamic = dynamic
        self.ansi_c = ansi_c


def _find_subst_end(s: str, start: int) -> int:
    """返回 $( 或子 shell ( 之后匹配右括号的下标；未闭合时返回 len(s)。尊重引号与转义。"""
    depth = 1
    j = start
    n = len(s)
    while j < n:
        c = s[j]
        if c == "\\":
            j += 2
            continue
        if c == "'":
            end = s.find("'", j + 1)
            j = n if end < 0 else end + 1
            continue
        if c == '"':
            j += 1
            while j < n and s[j] != '"':
                j += 2 if s[j] == "\\" else 1
            j += 1
            continue
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return j
        j += 1
    return n


def _find_backtick_end(s: str, start: int) -> int:
    """返回起始反引号之后匹配反引号的下标；尊重反斜杠转义。"""
    j = start
    n = len(s)
    while j < n:
        if s[j] == "\\":
            j += 2
            continue
        if s[j] == "`":
            return j
        j += 1
    return n


def scan_command(s: str, depth: int = 0) -> list:
    """把 shell 命令拆分为若干简单命令段（词元列表）。

    - 在引号外按 && / || / ; / | / & / 换行切分；子 shell 括号 (...) 递归拆段
    - $(...) / 反引号内部同样递归拆段（便于发现嵌套 git commit），所在词元标记 dynamic
    - $'...' 标记 ansi_c；双引号内允许转义，单引号内全字面
    """
    segments: list = []
    if depth > MAX_DEPTH:
        return segments
    current: list = []
    word_chars: list = []
    has_word = False
    dynamic = False
    ansi_c = False
    i = 0
    n = len(s)

    def flush_word():
        nonlocal has_word, dynamic, ansi_c, word_chars
        if has_word:
            current.append(Token("".join(word_chars), dynamic, ansi_c))
        word_chars = []
        has_word = False
        dynamic = False
        ansi_c = False

    def flush_segment():
        nonlocal current
        flush_word()
        if current:
            segments.append(current)
        current = []

    def recurse(inner: str):
        segments.extend(scan_command(inner, depth + 1))

    while i < n:
        c = s[i]
        if c in " \t":
            flush_word()
            i += 1
            continue
        if c in "\n;":
            flush_segment()
            i += 1
            continue
        if c in "&|":
            flush_segment()
            while i < n and s[i] in "&|":
                i += 1
            continue
        if c == "(":
            flush_segment()
            end = _find_subst_end(s, i + 1)
            recurse(s[i + 1:end])
            i = end + 1 if end < n else n
            continue
        if c == ")":
            flush_segment()
            i += 1
            continue
        has_word = True
        if c == "\\":
            if i + 1 < n:
                if s[i + 1] != "\n":
                    word_chars.append(s[i + 1])
                i += 2
            else:
                i += 1
            continue
        if c == "'":
            end = s.find("'", i + 1)
            if end < 0:
                word_chars.append(s[i + 1:])
                i = n
            else:
                word_chars.append(s[i + 1:end])
                i = end + 1
            continue
        if c == '"':
            i += 1
            while i < n and s[i] != '"':
                ch = s[i]
                if ch == "\\" and i + 1 < n:
                    nxt = s[i + 1]
                    if nxt in '$`"\\\n':
                        if nxt != "\n":
                            word_chars.append(nxt)
                        i += 2
                    else:
                        word_chars.append("\\")
                        i += 1
                    continue
                if ch == "$" and i + 1 < n and s[i + 1] == "(":
                    end = _find_subst_end(s, i + 2)
                    recurse(s[i + 2:end])
                    dynamic = True
                    i = end + 1 if end < n else n
                    continue
                if ch == "`":
                    end = _find_backtick_end(s, i + 1)
                    recurse(s[i + 1:end])
                    dynamic = True
                    i = end + 1 if end < n else n
                    continue
                word_chars.append(ch)
                i += 1
            i += 1
            continue
        if c == "$" and i + 1 < n and s[i + 1] == "'":
            ansi_c = True
            i += 2
            while i < n and s[i] != "'":
                if s[i] == "\\" and i + 1 < n:
                    word_chars.append(s[i + 1])
                    i += 2
                else:
                    word_chars.append(s[i])
                    i += 1
            i += 1
            continue
        if c == "$" and i + 1 < n and s[i + 1] == "(":
            end = _find_subst_end(s, i + 2)
            recurse(s[i + 2:end])
            dynamic = True
            i = end + 1 if end < n else n
            continue
        if c == "`":
            end = _find_backtick_end(s, i + 1)
            recurse(s[i + 1:end])
            dynamic = True
            i = end + 1 if end < n else n
            continue
        word_chars.append(c)
        i += 1
    flush_segment()
    return segments


def _basename(text: str) -> str:
    return text.rsplit("/", 1)[-1]


def strip_prefixes(tokens: list) -> list:
    """剥离 VAR=val / env / sudo / command / nohup / time 前缀，返回剩余词元。"""
    idx = 0
    n = len(tokens)
    while idx < n:
        t = tokens[idx].text
        if ENV_ASSIGN_RE.match(t):
            idx += 1
            continue
        base = _basename(t)
        if base == "env":
            idx += 1
            while idx < n:
                tt = tokens[idx].text
                if tt == "--":
                    idx += 1
                    break
                if ENV_ASSIGN_RE.match(tt):
                    idx += 1
                    continue
                if tt.startswith("-"):
                    opt = tt.split("=", 1)[0]
                    if opt in ENV_VALUE_OPTS and "=" not in tt and len(tt) == 2:
                        idx += 2
                    else:
                        idx += 1
                    continue
                break
            continue
        if base == "sudo":
            idx += 1
            while idx < n and tokens[idx].text.startswith("-"):
                tt = tokens[idx].text
                if tt == "--":
                    idx += 1
                    break
                opt = tt.split("=", 1)[0]
                if opt in SUDO_VALUE_OPTS and "=" not in tt and len(tt) == 2:
                    idx += 2
                else:
                    idx += 1
            continue
        if base in ("command", "nohup", "time"):
            idx += 1
            while idx < n and tokens[idx].text.startswith("-") and tokens[idx].text != "--":
                idx += 1
            if idx < n and tokens[idx].text == "--":
                idx += 1
            continue
        break
    return tokens[idx:]


def extract_shell_c(arg_tokens: list):
    """提取 sh/bash/zsh 的 -c 命令字符串词元（支持 -lc / -cfoo 等组合短参数）。"""
    i = 0
    n = len(arg_tokens)
    while i < n:
        t = arg_tokens[i].text
        if t == "--":
            break
        if t.startswith("--"):
            i += 2 if t in ("--rcfile", "--init-file") else 1
            continue
        if t.startswith("-") and len(t) > 1:
            cluster = t[1:]
            k = cluster.find("c")
            if k >= 0:
                rest = cluster[k + 1:]
                if rest:
                    return Token(rest, arg_tokens[i].dynamic, arg_tokens[i].ansi_c)
                return arg_tokens[i + 1] if i + 1 < n else None
            # bash/sh 的 -O/-o 带值；其余布尔短参数逐个跳过
            i += 2 if cluster[-1] in "Oo" else 1
            continue
        break
    return None


def find_git_subcommand(tokens: list):
    """跳过 git 全局选项，返回 (子命令名, 子命令参数词元)；无法确定时返回 (None, [])。"""
    idx = 1
    n = len(tokens)
    while idx < n:
        t = tokens[idx].text
        if t in GIT_VALUE_OPTS:
            idx += 2
            continue
        if t.startswith("--") and "=" in t and t.split("=", 1)[0] in GIT_VALUE_OPTS:
            idx += 1
            continue
        if (t.startswith("-C") or t.startswith("-c")) and len(t) > 2:
            idx += 1
            continue
        if t in GIT_BOOL_OPTS:
            idx += 1
            continue
        if t.startswith("-"):
            return None, []
        return t, tokens[idx + 1:]
    return None, []


def check_commit_args(arg_tokens: list):
    """校验 git commit 参数，返回违规原因字符串；合规则返回 None。"""
    messages: list = []
    amend = no_edit = help_flag = file_flag = False
    dynamic = ansi = False
    i = 0
    n = len(arg_tokens)

    def take_message(tok):
        nonlocal dynamic, ansi
        messages.append(tok.text)
        if tok.dynamic:
            dynamic = True
        if tok.ansi_c:
            ansi = True

    while i < n:
        tok = arg_tokens[i]
        t = tok.text
        if tok.dynamic:
            dynamic = True
        if tok.ansi_c:
            ansi = True
        if t == "--":
            for rest in arg_tokens[i + 1:]:
                if rest.dynamic:
                    dynamic = True
                if rest.ansi_c:
                    ansi = True
            break
        if t in ("--help", "-h"):
            help_flag = True
            i += 1
            continue
        if t in ("--message", "-m"):
            if i + 1 < n:
                take_message(arg_tokens[i + 1])
            i += 2
            continue
        if t.startswith("--message="):
            messages.append(t[len("--message="):])
            i += 1
            continue
        if t in ("--file", "-F") or t.startswith("--file=") or (t.startswith("-F") and len(t) > 2):
            file_flag = True
            i += 1
            continue
        if t.startswith("-m") and len(t) > 2:
            messages.append(t[2:])
            i += 1
            continue
        if t == "--amend":
            amend = True
            i += 1
            continue
        if t == "--no-edit":
            no_edit = True
            i += 1
            continue
        if t.startswith("--"):
            name = t.split("=", 1)[0]
            i += 2 if name in COMMIT_VALUE_LONG and "=" not in t else 1
            continue
        if t.startswith("-") and len(t) > 1:
            # 组合短参数：逐字符扫描，m/F/C/c/t 消耗附着值或下一个词元
            j = 1
            consumed_next = False
            while j < len(t):
                ch = t[j]
                if ch == "m":
                    rest = t[j + 1:]
                    if rest:
                        messages.append(rest)
                    elif i + 1 < n:
                        take_message(arg_tokens[i + 1])
                        consumed_next = True
                    break
                if ch == "F":
                    file_flag = True
                    break
                if ch == "h":
                    help_flag = True
                    break
                if ch in "Cct":
                    if not t[j + 1:] and i + 1 < n:
                        consumed_next = True
                    break
                if ch in "uS":
                    # 可选附着值：其余字符视为其值
                    break
                j += 1
            i += 2 if consumed_next else 1
            continue
        i += 1

    if dynamic:
        return REASON_SUBST
    if ansi:
        return REASON_ANSI
    if help_flag:
        return None
    if file_flag:
        return REASON_FILE
    if messages:
        return validate_message(messages)
    if amend and no_edit:
        return None
    return REASON_NO_MESSAGE


def validate_message(messages: list):
    """按 agy/rules/harness-config.md 的 Git Commit 规范校验提交信息。"""
    subject = messages[0].split("\n", 1)[0].strip()
    full = "\n\n".join(messages)

    m = SUBJECT_RE.match(subject)
    if not m:
        return (
            f"首行 '{subject}' 不符合 type(scope): subject 格式；"
            "请改为如 'fix(auth): 修复登录超时' 的格式（scope 可选）。"
        )
    typ, scope_grp, scope, subj = m.group(1), m.group(2), m.group(3), m.group(4).strip()
    if typ not in ALLOWED_TYPES:
        return (
            f"type '{typ}' 不在允许列表；仅允许英文小写 "
            "feat/fix/refactor/perf/test/docs/style/chore/build/ci/revert。"
        )
    if scope_grp is not None and not scope.strip():
        return "scope 括号内不可为空白；请删除空 scope 或填写有效范围，如 fix(auth):。"
    if not subj:
        return "subject 不可为空；请在 type: 后补充中文祈使句说明做了什么。"
    if subj.lower() in ZERO_INFO_SUBJECTS:
        return (
            f"subject '{subj}' 为零信息词；请说明具体做了什么，"
            "如 '修复登录超时' 而非 '修改'/'更新'/'fix'。"
        )
    if not CHINESE_RE.search(subj):
        return f"subject '{subj}' 缺少中文字符；请使用中文祈使句，如 '修复登录超时'。"
    if len(subj) > 50:
        return f"subject 长度 {len(subj)} 超过 50 字；请精简首行，细节移入 body（第二个 -m）。"
    if subj.endswith(("。", ".")):
        return "subject 不得以 。 或 . 结尾；请去掉末尾句号。"
    if PAST_DONE_RE.match(subj) or PAST_VERB_RE.match(subj):
        return (
            f"subject '{subj}' 以过去时开头；请改用祈使句动词开头，"
            "如 '增加'/'修复'/'重构'，不用 '已修复'/'修复了'。"
        )
    for line in full.splitlines():
        if AI_COAUTHOR_RE.match(line.strip()) and AI_NAME_RE.search(line):
            return (
                "提交信息含 AI 署名（Co-Authored-By 含 AI 工具/厂商标识）；"
                "请移除 Claude/Copilot/Cursor 等 AI 署名或等效辅助标识。"
            )
    if AI_ROBOT_GENERATED_RE.search(full) or any(
        AI_NAME_RE.search(m.group(1)) for m in AI_GENERATED_RE.finditer(full)
    ):
        return "提交信息含 'Generated with/by ...' AI 辅助标识；请移除后再提交。"
    if AI_ASSISTED_RE.search(full):
        return "提交信息含 'AI-assisted' 辅助标识；请移除后再提交。"
    return None


def analyze_segments(segments: list, depth: int = 0):
    """遍历命令段，返回首个 git commit 违规原因；全部合规则返回 None。"""
    if depth > MAX_DEPTH:
        return None
    for raw_tokens in segments:
        tokens = strip_prefixes(raw_tokens)
        if not tokens:
            continue
        base = _basename(tokens[0].text)
        if base in SHELL_NAMES:
            payload = extract_shell_c(tokens[1:])
            if payload is not None:
                if (payload.dynamic or payload.ansi_c) and SHELL_PAYLOAD_GIT_RE.search(
                    payload.text
                ):
                    return REASON_SUBST if payload.dynamic else REASON_ANSI
                reason = analyze_segments(scan_command(payload.text, depth + 1), depth + 1)
                if reason:
                    return reason
            continue
        if base not in ("git", "git1"):
            continue
        subcommand, args = find_git_subcommand(tokens)
        if subcommand != "commit":
            continue
        reason = check_commit_args(args)
        if reason:
            return reason
    return None


def guard_git_commit(payload: dict) -> dict:
    tool_call = payload.get("toolCall")
    if not isinstance(tool_call, dict):
        return {"decision": "allow"}
    args = tool_call.get("args")
    if not isinstance(args, dict):
        return {"decision": "allow"}
    name = tool_call.get("name")
    if isinstance(name, str) and name and name != "run_command":
        return {"decision": "allow"}
    command_line = args.get("CommandLine")
    if not isinstance(command_line, str) or not command_line.strip():
        return {"decision": "allow"}
    reason = analyze_segments(scan_command(command_line))
    if reason:
        return {"decision": "deny", "reason": reason}
    return {"decision": "allow"}


def main() -> None:
    try:
        raw = sys.stdin.read()
        payload = json.loads(raw) if raw.strip() else {}
        result = (
            guard_git_commit(payload)
            if isinstance(payload, dict)
            else {"decision": "allow"}
        )
    except Exception:
        result = {"decision": "allow"}
    json.dump(result, sys.stdout, ensure_ascii=False)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()